-- League context ---------------------------------------------------------------------------------------------

-- The league this request is about (see header comment). null = the caller is in no league.
create function lg() returns bigint
language sql stable security definer set search_path = public as $$
  select m.league_id from league_members m
  where m.name = me()
  order by m.league_id::text is not distinct from
             (nullif(current_setting('request.headers', true), '')::json ->> 'x-league') desc,
           m.joined_at, m.league_id
  limit 1
$$;

create function require_league() returns bigint
language plpgsql stable security definer set search_path = public as $$
declare l bigint := lg();
begin
  if l is null then raise exception 'not in a league' using errcode = 'P0002'; end if;
  return l;
end $$;

create function league_day(p_league bigint, p_at timestamptz default now()) returns date
language sql stable security definer set search_path = public as $$
  select ((p_at at time zone l.tz) - make_interval(hours => l.reset_hour)
          + case when l.reset_hour >= 12 then interval '1 day' else interval '0' end)::date
  from leagues l where l.league_id = p_league
$$;

-- When the league's current day ends.
create function league_reset_at(p_league bigint, p_at timestamptz default now()) returns timestamptz
language sql stable security definer set search_path = public as $$
  select (date_trunc('day', (p_at at time zone l.tz) - make_interval(hours => l.reset_hour))
          + interval '1 day' + make_interval(hours => l.reset_hour)) at time zone l.tz
  from leagues l where l.league_id = p_league
$$;

create function lg_today() returns date
language sql stable security definer set search_path = public as $$ select league_day(lg()) $$;

create function is_member(p_league bigint, p_name text) returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from league_members where league_id = p_league and name = p_name)
$$;

-- guest (anonymous sign-in) | legacy (name-only login) | verified (Google/Apple, or a confirmed real email)
create function account_kind() returns text
language sql stable security definer set search_path = public, auth as $$
  select case
    when coalesce(u.is_anonymous, false) then 'guest'
    when exists (select 1 from auth.identities i where i.user_id = u.id and i.provider <> 'email') then 'verified'
    when u.email not like '%@players.reidle.app' and u.email_confirmed_at is not null then 'verified'
    else 'legacy' end
  from auth.users u where u.id = auth.uid()
$$;

-- Private leagues (creating, joining) need a verified account; name-only accounts are let in while
-- app_flags.legacy_logins is on.
create function require_verified() returns void
language plpgsql stable security definer set search_path = public as $$
declare k text := account_kind();
begin
  if k = 'verified' or (k = 'legacy' and (select legacy_logins from app_flags)) then return; end if;
  raise exception 'sign in with Google, Apple or email to join private leagues' using errcode = '28000';
end $$;

create function require_commissioner(p_league bigint) returns text
language plpgsql stable security definer set search_path = public as $$
declare n text := require_me();
begin
  if not exists (select 1 from league_members where league_id = p_league and name = n and role = 'commissioner') then
    raise exception 'only the commissioner can do that' using errcode = '42501';
  end if;
  return n;
end $$;

create function league_brief(p_league bigint) returns jsonb
language sql stable security definer set search_path = public as $$
