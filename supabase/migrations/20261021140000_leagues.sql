drop function push_wanted(text);
create function push_wanted(p_kind text, p_league bigint) returns setof text
language sql stable security definer set search_path = public as $$
  select distinct s.name from push_subscriptions s
  join league_members m on m.name = s.name and m.league_id = p_league
  left join notify_prefs p on p.name = s.name
  where case p_kind
    when 'chat' then coalesce(p.chat, true)
    when 'results' then coalesce(p.results, false)
    when 'beaten' then coalesce(p.beaten, false)
    when 'challenges' then coalesce(p.challenges, false)
    when 'new_day' then coalesce(p.new_day, false)
    when 'recap' then coalesce(p.recap, false)
    else false end
$$;

-- Titles say which league when the recipients play in more than one.
