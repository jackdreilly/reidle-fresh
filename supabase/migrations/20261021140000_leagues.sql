create or replace function push_on_submission() returns trigger
language plpgsql security definer set search_path = public as $$
declare
  r bigint; total bigint; leader text; beaten text[];
  b record;
  q text := '?league=' || new.league_id;
begin
  if new.created_at < now() - interval '10 minutes' then return null; end if;

  if new.challenge_id is null then
    if new.day <> league_day(new.league_id) then return null; end if;
    select count(*) filter (where s."time" < new."time") + 1, count(*) into r, total
      from submissions s where s.league_id = new.league_id and s.day = new.day and s.challenge_id is null;
    select s.name into leader from submissions s
      where s.league_id = new.league_id and s.day = new.day and s.challenge_id is null
        and s.submission_id <> new.submission_id
      order by s."time", s.submission_id limit 1;
    for b in
      select s.name, s."time" from submissions s
      where s.league_id = new.league_id and s.day = new.day and s.challenge_id is null
        and s.name <> new.name and s."time" > new."time"
        and s.name in (select push_wanted('beaten', new.league_id))
    loop
      beaten := beaten || b.name;
      if r = 1 and b.name = leader then
        perform push_enqueue(array[b.name], push_title(new.league_id, '👑 ' || new.name || ' took 1st place from you'),
          push_secs(new."time") || ' vs your ' || push_secs(b."time"), '/stats/today' || q,
          'beaten-' || new.league_id || '-' || new.day);
      else
        perform push_enqueue(array[b.name], push_title(new.league_id, '⚡ ' || new.name || ' beat your time'),
          push_secs(new."time") || ' vs your ' || push_secs(b."time") || ' · ' || new.name || ' is ' || push_ordinal(r) || ' today',
          '/stats/today' || q, 'beaten-' || new.league_id || '-' || new.day);
      end if;
    end loop;
    perform push_enqueue(
      array(select push_wanted('results', new.league_id) except select new.name
            except select unnest(coalesce(beaten, '{}'))),
      push_title(new.league_id, new.name || ' finished today''s Reidle'),
      push_secs(new."time") || ' · ' || push_ordinal(r) || ' of ' || total || ' so far',
      '/stats/today' || q, 'results-' || new.league_id || '-' || new.day);
  else
    select count(*) into total from submissions s where s.challenge_id = new.challenge_id;
    if total = 1 then
      perform push_enqueue(array(select push_wanted('challenges', new.league_id) except select new.name),
        push_title(new.league_id, '🎯 ' || new.name || ' set a challenge'), push_secs(new."time") || ' · can you beat it?',
        '/challenges/challenge/' || new.challenge_id || q, 'challenge-' || new.challenge_id);
    else
      for b in
        select s.name, s."time" from submissions s
        where s.challenge_id = new.challenge_id and s.name <> new.name and s."time" > new."time"
          and s.name in (select push_wanted('challenges', new.league_id))
      loop
        perform push_enqueue(array[b.name], push_title(new.league_id, '🎯 ' || new.name || ' beat you on a challenge'),
          push_secs(new."time") || ' vs your ' || push_secs(b."time"),
          '/challenges/challenge/' || new.challenge_id || q, 'challenge-' || new.challenge_id);
      end loop;
    end if;
  end if;
  return null;
end $$;

-- Scheduled pushes, on each league's own clock: reminders N hours before its reset, the new word right after
-- it, and the weekly recap on the first hour of its Monday. Each job runs once per league per league-day.
create or replace function push_tick(p_at timestamptz default now()) returns integer
language plpgsql volatile security definer set search_path = public as $$
declare
  lr record;
  d date; left_h int; q text;
  played int; y_name text; y_time double precision; w jsonb; pl record; queued int;
begin
  for lr in
    select l.league_id from leagues l
    where exists (select 1 from league_members m join push_subscriptions s using (name) where m.league_id = l.league_id)
  loop
    d := league_day(lr.league_id, p_at);
    left_h := ceil(extract(epoch from league_reset_at(lr.league_id, p_at) - p_at) / 3600)::int;
    q := '?league=' || lr.league_id;

    if left_h between 1 and 23 then
      insert into push_jobs values ('reminder-' || lr.league_id || '-' || left_h, d) on conflict do nothing;
      if found then
        select count(*) into played from submissions
          where league_id = lr.league_id and day = d and challenge_id is null;
        perform push_enqueue(array(
            select p.name from notify_prefs p
            join league_members m on m.name = p.name and m.league_id = lr.league_id
            where p.reminder_before = left_h and p.name in (select name from push_subscriptions)
              and not exists (select 1 from submissions s where s.league_id = lr.league_id and s.day = d
                              and s.challenge_id is null and s.name = p.name)),
          push_title(lr.league_id, '⏰ Today''s Reidle ends in ' || left_h || (case when left_h = 1 then ' hour' else ' hours' end)),
          case played when 0 then 'Nobody has played yet. Go first!'
                      when 1 then '1 player has played. Your turn!'
                      else played || ' players have played. Your turn!' end,
          '/play' || q, 'reminder-' || lr.league_id || '-' || d);
      end if;
    end if;

    if left_h >= 24 then
      insert into push_jobs values ('new_day-' || lr.league_id, d) on conflict do nothing;
      if found then
        select name, "time" into y_name, y_time from submissions
          where league_id = lr.league_id and day = d - 1 and challenge_id is null
          order by "time", submission_id limit 1;
        perform push_enqueue(array(select push_wanted('new_day', lr.league_id)),
          push_title(lr.league_id, '🌅 A new Reidle word is up'),
          coalesce('Yesterday ' || y_name || ' won in ' || push_secs(y_time) || '.', 'Be the first to play today.'),
          '/play' || q, 'new-day-' || lr.league_id || '-' || d);
      end if;

      if extract(isodow from d) = 1 then
        insert into push_jobs values ('recap-' || lr.league_id, d) on conflict do nothing;
        if found then
          w := week_scores(lr.league_id, week_start(d - 7));
          if jsonb_array_length(w) > 0 then
            for pl in
              select n.name, (select x.i from jsonb_array_elements(w) with ordinality x(e, i) where x.e ->> 'name' = n.name) as place,
                     (select x.e #>> '{results,totals,score}' from jsonb_array_elements(w) x(e) where x.e ->> 'name' = n.name) as pts
              from push_wanted('recap', lr.league_id) n(name)
            loop
              perform push_enqueue(array[pl.name], push_title(lr.league_id, '🏆 ' || (w -> 0 ->> 'name') || ' won the week'),
                case when pl.place = 1 then 'That''s you! ' || pl.pts || ' points.'
                     when pl.place is not null then (w -> 0 #>> '{results,totals,score}') || ' points. You came '
                          || push_ordinal(pl.place) || ' of ' || jsonb_array_length(w) || ' with ' || pl.pts || '.'
                     else (w -> 0 #>> '{results,totals,score}') || ' points. You sat this one out.' end,
                '/stats/weekly/' || week_start(d - 7) || q, 'recap-' || lr.league_id || '-' || d);
            end loop;
          end if;
        end if;
      end if;
    end if;
  end loop;

  select count(*) into queued from push_outbox where created_at > now() - interval '1 hour';
  if queued > 0 and exists (select 1 from push_config) then
    perform net.http_post(url := (select url from push_config), body := '{}'::jsonb,
                          headers := '{"content-type":"application/json"}'::jsonb);
  end if;
  return queued;
end $$;

create or replace function push_flush_held() returns void
language plpgsql volatile security definer set search_path = public as $$
declare t record;
begin
  for t in
    select * from push_throttle
    where held > 0 and last_sent <= now() - push_cooldown(grp)
    for update skip locked
  loop
    update push_throttle set held = 0, held_at = null, last_sent = now() where name = t.name and grp = t.grp;
    -- already caught up on chat: nothing to say
    if t.grp = 'chat' and coalesce((select max(last_read) from message_reads where name = t.name), 'epoch') >= t.held_at then
      continue;
    end if;
    insert into push_outbox (recipients, title, body, url, tag)
    values (array[t.name], t.title || case when t.held > 1 then ' (+' || (t.held - 1) || ' more)' else '' end,
            t.body, t.url, t.tag);
  end loop;
end $$;

-- Admin (owner only), now per league (default: the founding league) -----------------------------------------------

drop function admin_remove_play(text, date, integer);
create function admin_remove_play(p_name text, p_day date default null, p_challenge_id integer default null,
                                  p_league bigint default 1)
returns jsonb
language plpgsql volatile security definer set search_path = public as $$
declare removed jsonb; w date; d date := coalesce(p_day, league_day(p_league));
begin
  with x as (
    delete from submissions
    where name = p_name
      and case when p_challenge_id is null then challenge_id is null and league_id = p_league and day = d
               else challenge_id = p_challenge_id end
    returning submission_id, day, "time", challenge_id)
  select coalesce(jsonb_agg(to_jsonb(x)), '[]') into removed from x;

  if p_challenge_id is null then
    delete from checkpoints where league_id = p_league and name = p_name and day = d;
    perform rerank(p_league, d);
    w := week_start(d);
    if p_league <> 1 or w >= scoring_cutover() then
      delete from winners where league_id = p_league and week = w and name = p_name;
    end if;
  end if;
  return jsonb_build_object('removed', removed);
end $$;

drop function admin_update_time(text, double precision, date, integer);
create function admin_update_time(p_name text, p_time double precision, p_day date default null,
                                  p_challenge_id integer default null, p_league bigint default 1)
returns jsonb
language plpgsql volatile security definer set search_path = public as $$
declare changed jsonb; w date; d date := coalesce(p_day, league_day(p_league));
begin
  with u as (
    update submissions s set "time" = p_time
    from (select submission_id, "time" as old_time from submissions
          where name = p_name
            and case when p_challenge_id is null then challenge_id is null and league_id = p_league and day = d
                     else challenge_id = p_challenge_id end) o
    where s.submission_id = o.submission_id
    returning s.submission_id, s.day, o.old_time, s."time" as new_time, s.challenge_id)
  select coalesce(jsonb_agg(to_jsonb(u)), '[]') into changed from u;

  if p_challenge_id is null and changed <> '[]'::jsonb then
    perform rerank(p_league, d);
    w := week_start(d);
    if p_league <> 1 or w >= scoring_cutover() then
      delete from winners where league_id = p_league and week = w;
    else
      delete from week_snapshots where league_id = 1 and week = w;
    end if;
  end if;
  return jsonb_build_object('changed', changed);
end $$;

