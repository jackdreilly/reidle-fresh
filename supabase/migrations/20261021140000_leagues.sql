$$;

-- Nicknames --------------------------------------------------------------------------------------------------

create function valid_nickname(p text) returns boolean
language sql immutable as $$ select p ~ '^[a-z0-9_]{3,15}$' $$;

-- A free nickname from a hint (Google name, email) or, for guests, a random adjective + animal.
create function pick_nickname(p_hint text, p_guest boolean) returns text
language plpgsql volatile security definer set search_path = public as $$
declare
  adj text[] := array['brisk','calm','clever','cosmic','daring','eager','fuzzy','gentle','happy','jolly','lucky',
                      'mellow','nimble','plucky','quick','quiet','rapid','sly','snappy','sunny','swift','witty','zesty'];
  animal text[] := array['otter','fox','owl','lynx','panda','koala','heron','moose','gecko','bison','crane','eagle',
                         'hare','ibis','lemur','marten','orca','puffin','raven','seal','tapir','wren','yak'];
  base text := left(regexp_replace(lower(coalesce(p_hint, '')), '[^a-z0-9_]', '', 'g'), 12);
  cand text;
begin
  if p_guest or length(base) < 3 then
    base := adj[1 + floor(random() * array_length(adj, 1))::int] || animal[1 + floor(random() * array_length(animal, 1))::int];
  end if;
  cand := base;
  for i in 1..50 loop
    exit when not exists (select 1 from players where name = cand);
    cand := left(base, 12) || (10 + floor(random() * (case when i < 20 then 90 else 990 end)))::int;
  end loop;
  return cand;
end $$;

-- Name-only login (legacy) passes the name in metadata. Everything else (guest, Google, Apple, email) gets
-- an auto-assigned nickname the player can change. Guests and brand-new name-only players start in Global.
create or replace function handle_new_user() returns trigger
language plpgsql security definer set search_path = public as $$
declare
  want text := new.raw_user_meta_data ->> 'name';
  nm text;
begin
  if want is not null then
    insert into players (name, user_id)
    values (want, new.id)
    on conflict (name) do update set user_id = excluded.user_id
      where players.user_id is null;
    if not exists (select 1 from league_members where name = want) then
      insert into league_members (league_id, name) values (2, want) on conflict do nothing;
    end if;
  else
    nm := pick_nickname(coalesce(new.raw_user_meta_data ->> 'preferred_username',
                                 new.raw_user_meta_data ->> 'full_name',
                                 split_part(new.email, '@', 1)),
                        coalesce(new.is_anonymous, false));
    insert into players (name, user_id, nickname_set) values (nm, new.id, false);
    if coalesce(new.is_anonymous, false) then
      insert into league_members (league_id, name) values (2, nm);
    end if;
  end if;
  return new;
end $$;

create function set_nickname(p_name text) returns jsonb
language plpgsql volatile security definer set search_path = public as $$
declare
  old text := require_me();
  nm text := lower(btrim(p_name));
begin
  if nm = old then
    update players set nickname_set = true where name = old;
    return jsonb_build_object('name', nm);
  end if;
  if not valid_nickname(nm) then
    raise exception 'nicknames are 3-15 letters, digits or _' using errcode = '22023';
  end if;
  if exists (select 1 from players where name = nm) then
    raise exception 'that nickname is taken' using errcode = '23505';
  end if;
  update players set name = nm, nickname_set = true where name = old;   -- foreign keys cascade
  -- plain-text references
  update messages set likes = array_replace(likes, old, nm) where old = any (likes);
  update winners set name = nm where name = old;
  update leagues set created_by = nm where created_by = old;
  update push_outbox set recipients = array_replace(recipients, old, nm) where old = any (recipients);
  update week_snapshots set results = (
    select jsonb_agg(case when e ->> 'name' = old then jsonb_set(e, '{name}', to_jsonb(nm)) else e end)
    from jsonb_array_elements(results) e)
  where results @> jsonb_build_array(jsonb_build_object('name', old));
  return jsonb_build_object('name', nm);
end $$;

-- Is this nickname free (for the picker, as you type)?
create function nickname_free(p_name text) returns boolean
language sql stable security definer set search_path = public as $$
  select valid_nickname(lower(btrim(p_name)))
     and (lower(btrim(p_name)) = me() or not exists (select 1 from players where name = lower(btrim(p_name))))
$$;

-- Daily game -------------------------------------------------------------------------------------------------

create or replace function played_today(p_name text) returns boolean
language sql stable security definer set search_path = public as $$
  select exists (
    select 1 from submissions
    where name = p_name and league_id = (select lg()) and day = (select lg_today()) and challenge_id is null)
$$;

drop function ensure_daily_word(date);
create function ensure_daily_word(p_league bigint, p_day date) returns daily_words
language plpgsql security definer set search_path = public as $$
declare r daily_words; a text;
begin
  select * into r from daily_words where league_id = p_league and day = p_day;
  if not found then
    a := (select answer from answers order by random() limit 1);
    insert into daily_words (league_id, day, word, answer)
    values (p_league, p_day, (select word from words where word <> a order by random() limit 1), a)
    on conflict (league_id, day) do nothing;
    select * into r from daily_words where league_id = p_league and day = p_day;
  end if;
  return r;
end $$;

create or replace function play_payload(p_name text) returns jsonb
language sql stable security definer set search_path = public as $$
  with ctx as (select lg() as l, lg_today() as d)
  select jsonb_build_object(
    'started', true,
    'startingWord', upper(dw.word), 'word', upper(dw.answer),
    'winner', lead.name, 'winnersTime', lead."time",
    'checkpoint', jsonb_build_object(
      'created_at', cp.created_at, 'penalty', cp.penalty, 'history', cp.history),
    'server_now', clock_timestamp())
  from ctx
  join checkpoints cp on cp.league_id = ctx.l and cp.name = p_name and cp.day = ctx.d
  join daily_words dw on dw.league_id = ctx.l and dw.day = ctx.d
  left join lateral (select name, "time" from submissions
    where league_id = ctx.l and day = ctx.d and challenge_id is null order by "time" limit 1) lead on true
$$;

create or replace function play_state() returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare
  n text := require_me();
  l bigint := require_league();
  d date := league_day(l);
  payload jsonb;
begin
  if played_today(n) then raise exception 'already played' using errcode = 'P0001'; end if;
  payload := play_payload(n);
  if payload is not null then return payload; end if;
  return (select jsonb_build_object('started', false, 'winner', s.name, 'winnersTime', s."time")
          from (select 1) x left join lateral (
            select name, "time" from submissions
            where league_id = l and day = d and challenge_id is null order by "time" limit 1) s on true);
end $$;

create or replace function start_play() returns jsonb
language plpgsql volatile security definer set search_path = public as $$
declare
  n text := require_me();
  l bigint := require_league();
  d date := league_day(l);
begin
  if played_today(n) then raise exception 'already played' using errcode = 'P0001'; end if;
  perform ensure_daily_word(l, d);
  insert into checkpoints (league_id, name, day, penalty, history)
  values (l, n, d, 0, '[]')
  on conflict (league_id, name) do update
    set day = excluded.day, penalty = 0, history = '[]', created_at = now()
    where checkpoints.day <> excluded.day;   -- idempotent: a second start never resets the clock
  return play_payload(n);
end $$;

create or replace function save_checkpoint(p_penalty double precision, p_history jsonb) returns void
language sql volatile security definer set search_path = public as $$
  update checkpoints
  set history = case when jsonb_array_length(p_history) >= jsonb_array_length(history)
                     then p_history else history end,
      penalty = greatest(penalty, p_penalty)
  where name = require_me() and league_id = (select lg()) and day = (select lg_today())
    and jsonb_typeof(p_history) = 'array'
$$;

drop function rerank_today();
create function rerank(p_league bigint, p_day date) returns void
language sql volatile security definer set search_path = public as $$
  update submissions s set "rank" = r.rn
  from (select submission_id,
          row_number() over (order by "time", submission_id) as rn
        from submissions where league_id = p_league and day = p_day and challenge_id is null) r
  where s.submission_id = r.submission_id and s."rank" <> r.rn
$$;

create or replace function submit_daily(
  p_time double precision, p_penalty double precision, p_playback jsonb,
  p_word text, p_paste text
) returns void
language plpgsql volatile security definer set search_path = public as $$
declare
  n text := require_me();
  l bigint := require_league();
  d date := league_day(l);
begin
  if played_today(n) then raise exception 'already played' using errcode = 'P0001'; end if;
  insert into submissions (league_id, day, name, "time", penalty, playback, word, paste)
  values (l, d, n, p_time, p_penalty, p_playback, p_word, p_paste);
  perform rerank(l, d);
end $$;

