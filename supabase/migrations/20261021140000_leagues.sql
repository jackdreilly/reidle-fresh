  n text := require_me();
  l bigint := (select league_id from challenges where challenge_id = p_challenge_id);
begin
  if not is_member(l, n) then raise exception 'not in this league' using errcode = '42501'; end if;
  insert into submissions (league_id, day, challenge_id, name, "time", penalty, playback, word, paste)
  values (l, league_day(l), p_challenge_id, n, p_time, p_penalty, p_playback, p_word, p_paste);
  return jsonb_build_object('pending_challenges',
    (select count(*) from pending_challenge_ids(n)));
