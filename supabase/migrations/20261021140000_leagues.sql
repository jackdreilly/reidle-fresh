-- The league's scoring settings decide each day's points. p_additive = false is the founding league's legacy
-- product score (geometric rank), frozen for weeks before the scoring cutover.
create function week_scores_calc(p_league bigint, p_week date, p_additive boolean) returns jsonb
language sql stable security definer set search_path = public as $$
  with params as (
    select week_start(p_week) as s, p_additive as is_new,
           coalesce(l.scoring ->> 'mode', 'table') as mode, l.scoring -> 'points' as pts,
           coalesce((l.scoring ->> 'no_show')::numeric, 0) as no_show,
           (l.scoring ->> 'best_of')::int as best_of
    from leagues l where l.league_id = p_league),
  subs as (
    select sb.day, sb.name, sb."time", sb.submission_id
    from submissions sb, params
    where sb.league_id = p_league and sb.challenge_id is null and sb.day between params.s and params.s + 6),
  names as (select distinct name from subs),
  days as (select distinct day from subs),
  pen as (select day, least(300, max("time") + 120) as pt, count(*) as field from subs group by day),
  grid as (
    select n.name, d.day, s.submission_id, s."time" is not null as played, pen.field,
           coalesce(s."time", pen.pt) as round_time
    from names n cross join days d
    join pen on pen.day = d.day
    left join subs s on s.name = n.name and s.day = d.day),
  ranked as (
    select *, case when played then row_number() over (
      partition by day order by played desc, round_time, name) end as day_rank
    from grid),
  scored as (
    select name, day, round_time, submission_id, is_new,
      case when played then least(day_rank, 9) else 10 end as score,
      case when not played then no_show
           when mode = 'field' then 1 + field - day_rank
           else coalesce((pts ->> (day_rank::int - 1))::numeric, 0) end as points
    from ranked, params),
  counted as (
    select scored.*, params.best_of is null
             or row_number() over (partition by name order by points desc, day) <= params.best_of as counts
    from scored, params),
  agg as (
    select name,
      jsonb_agg(jsonb_build_object(
        'day', day, 'time', round_time,
        'score', case when is_new then points else score end,
        'counted', counts,
        'submission_id', submission_id) order by day) as days,
      round(sum(round_time))::int as total_time,
      case when bool_or(is_new) then coalesce(sum(points) filter (where counts), 0)
           else round(exp(sum(ln(score))))::numeric end as total_score,
      bool_or(is_new) as is_new,
      coalesce(sum(points) filter (where counts), 0) as pts, exp(sum(ln(score))) as prod
    from counted group by name)
  select coalesce(jsonb_agg(jsonb_build_object(
      'name', name,
      'results', jsonb_build_object('days', days, 'totals',
        jsonb_build_object('time', total_time, 'score', total_score)))
    order by case when is_new then pts end desc nulls last,
             case when not is_new then prod end nulls last,
             total_time, name), '[]')
  from agg
$$;

create function week_scores(p_league bigint, p_week date) returns jsonb
language plpgsql volatile security definer set search_path = public as $$
declare w date := week_start(p_week); r jsonb;
begin
  if p_league <> 1 or w >= scoring_cutover() then
    return week_scores_calc(p_league, w, true);
  end if;
  select results into r from week_snapshots where league_id = 1 and week = w;
  if r is null then
    r := week_scores_calc(1, w, false);
    if r <> '[]'::jsonb then
      insert into week_snapshots (league_id, week, results) values (1, w, r) on conflict do nothing;
    end if;
  end if;
  return r;
end $$;

create function last_week_winner(p_league bigint) returns text
language plpgsql volatile security definer set search_path = public as $$
declare w date := week_start(league_day(p_league) - 7); n text;
begin
  select name into n from winners where league_id = p_league and week = w;
  if n is null then
    select r ->> 'name' into n from jsonb_array_elements(week_scores(p_league, w)) r limit 1;
    if n is not null then
      insert into winners (league_id, week, name) values (p_league, w, n) on conflict do nothing;
    end if;
  end if;
  return n;
end $$;

create function weekly_page(p_week date) returns jsonb
language plpgsql volatile security definer set search_path = public as $$
declare l bigint := require_league();
begin
  return jsonb_build_object('players', week_scores(l, p_week),
    'additive', l <> 1 or week_start(p_week) >= scoring_cutover(),
    'scoring', (select scoring from leagues where league_id = l));
end $$;

create or replace function daily_page(p_day date) returns jsonb
language plpgsql volatile security definer set search_path = public as $$
declare
  n text := require_me();
  l bigint := require_league();
  mine boolean := played_today(n);
  is_today boolean := p_day = league_day(l);
  rows jsonb;
begin
  select coalesce(jsonb_agg(jsonb_build_object(
      'submission_id', submission_id, 'name', name, 'time', "time",
      'penalty', penalty,
      'paste', case when is_today and not mine then '' else paste end)
    order by "rank"), '[]')
  into rows from submissions where league_id = l and day = p_day and challenge_id is null;
  return jsonb_build_object(
    'submissions', rows, 'is_today', is_today,
    'winner', case when is_today then coalesce(last_week_winner(l), 'no winner') end);
end $$;

