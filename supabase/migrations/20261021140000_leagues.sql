-- Leagues. Every group of players lives in a league: its own daily word, reset time, scoring, weekly
-- winners, challenges and chat. Battles stay global.
--
--   league 1 "Reidle OG"     everyone who played before leagues (all history moves here as-is)
--   league 2 "Reidle Global" public: guests land here, anyone can join (invite code 'global')
--
-- Which league a request is about: the client sends an `x-league: <id>` header with every RPC. lg() reads it
-- and only honours it when the caller is a member, otherwise falls back to the caller's first league. That
-- keeps every RPC signature as it was (the old client keeps working: no header = your first league).
--
-- A league's day: the date at its reset hour in its timezone (league_day). Reset hours from 12:00 label the
-- evening's game with the next date, so "resets at 9pm" plays tomorrow's word tonight.
--
-- Every table that is per league gets league_id with default 1, so pre-league inserts (imports, fixtures) land
-- in the founding league. RPCs always pass it explicitly.

-- Tables ---------------------------------------------------------------------------------------------------

create table leagues (
  league_id bigint generated by default as identity primary key,
  name text not null check (length(btrim(name)) between 1 and 40),
  invite_code text not null unique default substr(md5(random()::text || clock_timestamp()::text), 1, 10),
  is_public boolean not null default false,
  tz text not null default 'UTC',
  reset_hour integer not null default 0 check (reset_hour between 0 and 23),
  -- mode 'table': points[rank-1] (0 beyond the list) · mode 'field': 1 + players you beat
  -- no_show: points for a day you skipped · best_of: only your best N days count toward the week (null = all)
  scoring jsonb not null default '{"mode":"table","points":[40,20,10,7,6,5,4,3,2,1],"no_show":0,"best_of":null}',
  created_by text,   -- a player name (no foreign key, so truncating players in tests keeps the leagues)
  created_at timestamptz not null default now()
);
