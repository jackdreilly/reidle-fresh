create function create_league(p_name text, p_tz text default 'UTC', p_reset_hour integer default 0) returns bigint
language plpgsql volatile security definer set search_path = public as $$
declare
  n text := require_me();
  id bigint;
begin
  perform require_verified();
  if (select count(*) from leagues where created_by = n) >= 10 then
    raise exception 'you can run at most 10 leagues' using errcode = '54000';
  end if;
  if not exists (select 1 from pg_timezone_names where name = p_tz) then
    raise exception 'unknown timezone %', p_tz using errcode = '22023';
  end if;
  insert into leagues (name, tz, reset_hour, created_by) values (btrim(p_name), p_tz, p_reset_hour, n)
  returning league_id into id;
  insert into league_members (league_id, name, role) values (id, n, 'commissioner');
  return id;
end $$;

create function join_league(p_code text) returns bigint
language plpgsql volatile security definer set search_path = public as $$
declare
  n text := require_me();
  lgr leagues;
begin
  select * into lgr from leagues where invite_code = lower(btrim(p_code));
  if not found then raise exception 'that invite link is no longer valid' using errcode = 'P0002'; end if;
  if not lgr.is_public then perform require_verified(); end if;
  insert into league_members (league_id, name) values (lgr.league_id, n) on conflict do nothing;
  return lgr.league_id;
end $$;

-- Leaving hands the commissioner role to the longest-standing member if you were the last one.
create function leave_league(p_league bigint) returns void
language plpgsql volatile security definer set search_path = public as $$
declare n text := require_me();
begin
  delete from league_members where league_id = p_league and name = n;
  if not exists (select 1 from league_members where league_id = p_league and role = 'commissioner') then
    update league_members set role = 'commissioner'
    where (league_id, name) = (select league_id, name from league_members where league_id = p_league
                               order by joined_at, name limit 1);
  end if;
end $$;

-- Commissioner: change any of name, tz, reset_hour, scoring; {"new_invite": true} makes a fresh link.
create function update_league(p jsonb) returns jsonb
language plpgsql volatile security definer set search_path = public as $$
declare
  l bigint := require_league();
  sc jsonb := p -> 'scoring';
begin
  perform require_commissioner(l);
  if p ? 'tz' and not exists (select 1 from pg_timezone_names where name = p ->> 'tz') then
    raise exception 'unknown timezone %', p ->> 'tz' using errcode = '22023';
  end if;
  if sc is not null and not (
       coalesce(sc ->> 'mode', 'table') in ('table', 'field')
       and (sc -> 'points' is null or (jsonb_typeof(sc -> 'points') = 'array'
            and jsonb_array_length(sc -> 'points') between 1 and 30
            and not exists (select 1 from jsonb_array_elements(sc -> 'points') e
                            where jsonb_typeof(e) <> 'number' or abs(e::text::numeric) > 1000)))
       and (sc ->> 'no_show' is null or abs((sc ->> 'no_show')::numeric) <= 1000)
       and (sc ->> 'best_of' is null or (sc ->> 'best_of')::int between 1 and 7)) then
    raise exception 'invalid scoring settings' using errcode = '22023';
  end if;
  update leagues set
    name = coalesce(nullif(btrim(p ->> 'name'), ''), name),
    tz = coalesce(p ->> 'tz', tz),
    reset_hour = coalesce((p ->> 'reset_hour')::int, reset_hour),
    scoring = case when sc is null then scoring else jsonb_build_object(
      'mode', coalesce(sc ->> 'mode', 'table'),
      'points', coalesce(sc -> 'points', scoring -> 'points'),
      'no_show', coalesce((sc ->> 'no_show')::numeric, 0),
      'best_of', (sc ->> 'best_of')::int) end,
    invite_code = case when (p ->> 'new_invite')::boolean
                       then substr(md5(random()::text || clock_timestamp()::text), 1, 10) else invite_code end
  where league_id = l;
  -- results memoised under the old settings
  if sc is not null then
    delete from winners where league_id = l and week >= week_start(league_day(l) - 7)
      and (l <> 1 or week >= scoring_cutover());
  end if;
  return league_page();
end $$;

-- Commissioner: p_role 'commissioner' | 'member' | 'remove'.
create function set_member(p_name text, p_role text) returns jsonb
language plpgsql volatile security definer set search_path = public as $$
declare l bigint := require_league(); n text;
begin
  n := require_commissioner(l);
  if p_role = 'remove' then
    if p_name = n then raise exception 'use leave instead' using errcode = '22023'; end if;
    delete from league_members where league_id = l and name = p_name;
  elsif p_role in ('commissioner', 'member') then
    update league_members set role = p_role where league_id = l and name = p_name;
    if not exists (select 1 from league_members where league_id = l and role = 'commissioner') then
      raise exception 'a league needs a commissioner' using errcode = '22023';
    end if;
  else
    raise exception 'unknown role %', p_role using errcode = '22023';
  end if;
  return league_page();
end $$;

