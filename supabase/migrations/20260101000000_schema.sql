-- Lock every table; RPCs (security definer) are the only door.
alter table players enable row level security;
alter table words enable row level security;
alter table answers enable row level security;
alter table daily_words enable row level security;
alter table challenges enable row level security;
alter table submissions enable row level security;
alter table checkpoints enable row level security;
alter table messages enable row level security;
alter table message_reads enable row level security;
alter table winners enable row level security;
alter table battles enable row level security;

revoke all on all tables in schema public from anon, authenticated;
revoke all on all sequences in schema public from anon, authenticated;

-- Battles: live rooms are written by the clients (broadcast + state sync).
grant select, update on battles to authenticated;
create policy battles_read on battles for select to authenticated using (true);
create policy battles_write on battles for update to authenticated
  using (true) with check (true);
alter publication supabase_realtime add table battles;
alter table battles replica identity full;

-- Name-only auth: the auth trigger links (or creates) the player row.
create function handle_new_user() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  insert into players (name, user_id)
  values (new.raw_user_meta_data ->> 'name', new.id)
  on conflict (name) do update set user_id = excluded.user_id
    where players.user_id is null;
  return new;
end $$;
create trigger on_auth_user_created after insert on auth.users
  for each row execute function handle_new_user();
