-- Reidle schema. All app access goes through the RPCs in the next migration;
-- tables are closed to clients except `battles` (realtime + direct state writes).

create table players (
  name text primary key,
  user_id uuid unique references auth.users (id) on delete set null,
  created_at timestamptz not null default now()
);

create table words (word text primary key);
create table answers (answer text primary key);

create table daily_words (
  day date primary key,
  word text not null references words (word),
  answer text not null references answers (answer)
);

create table challenges (
  challenge_id integer generated always as identity primary key,
  starting_word text not null references words (word),
  answer text not null references answers (answer),
  created_at timestamptz not null default now()
);
create index challenges_created_at_idx on challenges (created_at);

create table submissions (
  submission_id bigint generated always as identity primary key,
  day date not null default current_date,
  name text not null references players (name),
  paste text not null default '',
  playback jsonb not null default '{"events":[]}',
  challenge_id integer references challenges (challenge_id),
  "time" double precision not null check ("time" > 0),
  penalty double precision not null default 0 check (penalty >= 0),
  word text not null,
  "rank" integer not null default 1,
  created_at timestamptz not null default now()
);
create unique index submissions_daily_once on submissions (day, name)
  where challenge_id is null;
create unique index submissions_challenge_once on submissions (challenge_id, name)
  where challenge_id is not null;
create index submissions_day_idx on submissions (day);
create index submissions_name_idx on submissions (name);
create index submissions_challenge_idx on submissions (challenge_id);

create table checkpoints (
  name text primary key references players (name),
  day date not null default current_date,
  penalty double precision not null default 0,
  history jsonb not null default '[]',
  created_at timestamptz not null default now()
);

create table messages (
  message_id integer generated always as identity primary key,
  name text not null references players (name),
  message text not null check (length(message) between 1 and 4000),
  likes text[] not null default '{}',
  created_at timestamptz not null default now()
);
create index messages_created_at_idx on messages (created_at desc);

create table message_reads (
  name text primary key references players (name),
  last_read timestamptz not null
);

create table winners (
  week date primary key,
  name text not null
);

create table battles (
  battle_id integer generated by default as identity primary key,
  state jsonb not null default '{}',
  users jsonb not null default '[]',
  updated_at timestamptz not null default now()
);
