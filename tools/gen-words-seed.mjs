// Regenerates supabase/seed/words.sql (local/staging fixture word tables) from src/data/*.csv,
// the same lists the client validates guesses against. Words are stored UPPERCASE like prod.
// Prod's own word tables arrive via clone/import, never via migrations.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
const list = (f) => [...new Set(readFileSync(new URL(`../src/data/${f}`, import.meta.url), "utf8").split(/\s+/).filter(Boolean).map((w) => w.toUpperCase()))];
const ins = (table, col, words) => `insert into ${table} (${col}) select unnest(string_to_array($w$${words.join(",")}$w$, ',')) on conflict do nothing;\n`;
mkdirSync(new URL("../supabase/seed/", import.meta.url), { recursive: true });
writeFileSync(
  new URL("../supabase/seed/words.sql", import.meta.url),
  "-- generated by tools/gen-words-seed.mjs; do not edit\n" + ins("words", "word", list("words.csv")) + ins("answers", "answer", list("answers.csv")),
);
