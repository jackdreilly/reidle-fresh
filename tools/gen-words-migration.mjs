// Regenerates the reference-data migration from src/data/*.csv (single source of truth
// for both the client word check and the database).
import { readFileSync, writeFileSync } from "node:fs";
const list = (f) => [...new Set(readFileSync(new URL(`../src/data/${f}`, import.meta.url), "utf8").split(/\s+/).filter(Boolean).map((w) => w.toLowerCase()))];
const ins = (table, col, words) => `insert into ${table} (${col}) select unnest(string_to_array($w$${words.join(",")}$w$, ',')) on conflict do nothing;\n`;
writeFileSync(
  new URL("../supabase/migrations/20260101000200_word_lists.sql", import.meta.url),
  "-- generated by tools/gen-words-migration.mjs; do not edit\n" + ins("words", "word", list("words.csv")) + ins("answers", "answer", list("answers.csv")),
);
